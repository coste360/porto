#!/usr/bin/env node
// Builds the documentation palette from the single theme of the web apps,
// web/shared/src/styles/globals.css (ADR 0007), so the docs use the same
// colours, radius and font as the panel and the public booking page without
// keeping a second copy of the values.
//
// Only the custom properties are taken: the light block (`:root { ... }`), the
// dark block (`.dark { ... }`, re-targeted to Starlight's
// `:root[data-theme='dark']`) and the `--font-sans` stack of `@theme inline`
// (published as `--porto-font`). Tailwind, its utilities and the base layer of
// the SPAs are not needed by the docs and are left out. If the shape of the
// shared file changes, the script fails instead of writing a partial theme.
//
// It also checks that the brand files under public/brand/ and the favicons are
// byte-identical to the originals in assets/brand/ (ADR 0007: copies are never
// edited or redrawn).
//
// Output: src/styles/generated/theme.css (git-ignored, rebuilt by predev,
// prebuild and precheck).
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const docsRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(docsRoot, '..');
const source = join(repoRoot, 'web', 'shared', 'src', 'styles', 'globals.css');
const outFile = join(docsRoot, 'src', 'styles', 'generated', 'theme.css');

const fail = (message) => {
  console.error(`sync-theme: ${message}`);
  process.exit(1);
};

/** Body of the first top-level rule whose selector line is exactly `selector {`. */
function ruleBody(css, selector) {
  const lines = css.split('\n');
  const start = lines.findIndex((line) => line.trim() === `${selector} {`);
  if (start < 0) fail(`no "${selector} {" block in web/shared/src/styles/globals.css`);
  const end = lines.findIndex((line, i) => i > start && line.trim() === '}');
  if (end < 0) fail(`unterminated "${selector}" block in globals.css`);
  return lines.slice(start + 1, end);
}

/** Custom property declarations (`--name: value;`) of a block, comments dropped. */
function declarations(body, selector) {
  const decls = body
    .map((line) => line.trim())
    .filter((line) => line.startsWith('--') || line.startsWith('color-scheme:'));
  if (decls.length < 10) fail(`"${selector}" has only ${decls.length} declarations: shape changed`);
  for (const d of decls) {
    if (!d.endsWith(';')) fail(`multi-line declaration in "${selector}": ${d}`);
  }
  return decls;
}

const css = readFileSync(source, 'utf8');
const light = declarations(ruleBody(css, ':root'), ':root');
const dark = declarations(ruleBody(css, '.dark'), '.dark');
const font = ruleBody(css, '@theme inline')
  .map((line) => line.trim())
  .find((line) => line.startsWith('--font-sans:'));
if (!font) fail('no --font-sans in the @theme inline block of globals.css');
for (const required of ['--primary:', '--background:', '--foreground:', '--border:', '--link:']) {
  if (!light.some((d) => d.startsWith(required))) fail(`light theme without ${required}`);
  if (!dark.some((d) => d.startsWith(required))) fail(`dark theme without ${required}`);
}

const indent = (decls) => decls.map((d) => `  ${d}`).join('\n');
const out = `/* GENERATED by docs-site/scripts/sync-theme.mjs from web/shared/src/styles/globals.css.
   Do not edit: change the shared theme and rebuild the docs. */
:root {
${indent(light)}
  ${font.replace('--font-sans:', '--porto-font:')}
}

:root[data-theme='dark'] {
${indent(dark)}
}
`;
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);
console.log(`sync-theme: ${relative(docsRoot, outFile)} <- web/shared/src/styles/globals.css`);

// Brand copies: public path -> original in assets/brand/.
const brandCopies = {
  'public/brand/porto/porto_logo_horizontal_primary.svg': 'porto/outlined/porto_logo_horizontal_primary.svg',
  'public/brand/porto/porto_logo_horizontal_inverted_2color.svg':
    'porto/outlined/porto_logo_horizontal_inverted_2color.svg',
  'public/brand/coste360/logo-primary.svg': 'coste360/logo-primary.svg',
  'public/brand/coste360/logo-white.svg': 'coste360/logo-white.svg',
  'public/brand/coste360/icon-primary.svg': 'coste360/icon-primary.svg',
  'public/brand/coste360/icon-white.svg': 'coste360/icon-white.svg',
  'public/favicon.svg': 'porto/06_Favicon_Web/favicon.svg',
  'public/favicon-32x32.png': 'porto/06_Favicon_Web/favicon-32x32.png',
  'public/apple-touch-icon.png': 'porto/06_Favicon_Web/apple-touch-icon.png',
  'public/og.png': 'porto/10_Materiale_Social/porto_social_og_1200x630.png',
};
const sha = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');
for (const [copy, original] of Object.entries(brandCopies)) {
  if (sha(join(docsRoot, copy)) !== sha(join(repoRoot, 'assets', 'brand', original))) {
    fail(`${copy} differs from assets/brand/${original}: copy the original file unchanged`);
  }
}
console.log(`sync-theme: ${Object.keys(brandCopies).length} brand files identical to assets/brand/`);
