// Command gentrig writes sintable_gen.go: sin(i × 0.1°) × 1e9 rounded half-even for i = 0..900.
//
// It runs through `go generate ./internal/geo/...` from the internal/geo directory. Floats are allowed here
// only: the runtime geometry reads the committed integer table.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
)

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/geo/internal/gentrig; DO NOT EDIT.\n\n")
	b.WriteString("package geo\n\n")
	b.WriteString("// sinTable[i] = round_half_even(sin(i × 0.1°) × TrigScale), i = 0..900.\n")
	b.WriteString("var sinTable = [901]int64{\n")
	for i := 0; i <= 900; i++ {
		v := math.RoundToEven(math.Sin(float64(i)*math.Pi/1800) * 1e9)
		switch i {
		case 0:
			v = 0
		case 900:
			v = 1e9
		}
		fmt.Fprintf(&b, "\t%d,", int64(v))
		if i%8 == 7 || i == 900 {
			b.WriteByte('\n')
		} else {
			b.WriteByte(' ')
		}
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	out := "sintable_gen.go"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	if err := os.WriteFile(out, src, 0o644); err != nil { //nolint:gosec // generated source file, world-readable by design
		log.Fatal(err)
	}
}
