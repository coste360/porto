// Queries of deadlines and deadline_policies (m1-plan §3.1, §3.2). Every function is scoped by the marina.

// Urgency values computed when deadlines are read (m1-plan §3.2).
const (
	UrgencyOverdue = "overdue"
	UrgencyDueSoon = "due_soon"
	UrgencyLater   = "later"
)

// DeadlineFilter narrows ListDeadlines. Statuses empty = every status. Urgency needs Today and the lead days:
// SoonUntil maps each kind to the last date that is still "due soon"; kinds not listed use DefaultSoonUntil.
type DeadlineFilter struct {
	Statuses         []string
	Kind             string
	CustomerID       string
	VesselID         string
	DueBefore        calendar.Date // due on or before
	DueAfter         calendar.Date // due on or after
	Urgency          string
	Today            calendar.Date
	SoonUntil        map[string]calendar.Date
	DefaultSoonUntil calendar.Date
	// CustomerOrVessels selects deadlines of a customer or of any of the vessels (customer overview).
	CustomerOrVessels *CustomerVessels
}

// CustomerVessels is a customer id with the ids of its vessels.
type CustomerVessels struct {
	CustomerID string
	VesselIDs  []string
}

// deadlineCursorPrefix versions the (due_on, id) cursor of ListDeadlines.
const deadlineCursorPrefix = "d1:"

func encodeDeadlineCursor(d *Deadline) string {
	return base64.RawURLEncoding.EncodeToString([]byte(deadlineCursorPrefix + d.DueOn.String() + "|" + d.ID))
}

func decodeDeadlineCursor(c string) (calendar.Date, string, error) {
	if c == "" {
		return calendar.Date{}, "", nil
	}
	b, err := base64.RawURLEncoding.DecodeString(c)
	if err != nil {
		return calendar.Date{}, "", ErrInvalidCursor
	}
	rest, ok := strings.CutPrefix(string(b), deadlineCursorPrefix)
	if !ok {
		return calendar.Date{}, "", ErrInvalidCursor
	}
	day, id, ok := strings.Cut(rest, "|")
	if !ok || !ValidID(id) {
		return calendar.Date{}, "", ErrInvalidCursor
	}
	d, err := calendar.Parse(day)
	if err != nil {
		return calendar.Date{}, "", ErrInvalidCursor
	}
	return d, id, nil
}

// InsertDeadline inserts a deadline.
func InsertDeadline(ctx context.Context, db bun.IDB, d *Deadline) error {
	_, err := db.NewInsert().Model(d).Exec(ctx)
	if IsUniqueViolation(err) {
		return ErrConflict
	}
	return err
}

// GetDeadline returns one deadline of a marina.
func GetDeadline(ctx context.Context, db bun.IDB, s MarinaScope, id string) (*Deadline, error) {
	if !ValidID(id) {
		return nil, ErrNotFound
	}
	d := new(Deadline)
	if err := db.NewSelect().Model(d).Where("marina_id = ?", s.ID()).Where("id = ?", id).Scan(ctx); err != nil {
		return nil, notFound(err)
	}
	return d, nil
}

// DeadlinesOfSource returns the deadlines generated by one source row (e.g. a document).
func DeadlinesOfSource(ctx context.Context, db bun.IDB, s MarinaScope, sourceType, sourceID string) ([]Deadline, error) {
	out := []Deadline{}
	err := db.NewSelect().Model(&out).Where("marina_id = ?", s.ID()).Where("source_type = ?", sourceType).
		Where("source_id = ?", sourceID).OrderExpr("id").Scan(ctx)
	return out, err
}

// DeleteDeadlinesOfSource removes the deadlines of a source row, except those of keepKind ("" = all).
func DeleteDeadlinesOfSource(ctx context.Context, db bun.IDB, s MarinaScope, sourceType, sourceID, keepKind string) error {
	q := db.NewDelete().Table("deadlines").Where("marina_id = ?", s.ID()).Where("source_type = ?", sourceType).
		Where("source_id = ?", sourceID)
	if keepKind != "" {
		q = q.Where("kind <> ?", keepKind)
	}
	_, err := q.Exec(ctx)
	return err
}

// DeleteDeadlinesOfCustomer removes every deadline of a customer (anonymisation).
func DeleteDeadlinesOfCustomer(ctx context.Context, db bun.IDB, s MarinaScope, customerID string) error {
	_, err := db.NewDelete().Table("deadlines").Where("marina_id = ?", s.ID()).Where("customer_id = ?", customerID).Exec(ctx)
	return err
}

var deadlineColumns = []string{"kind", "customer_id", "vessel_id", "due_on", "status", "note", "updated_at"}

// UpdateDeadline writes the editable columns when the stored version equals ifMatch and bumps the version.
func UpdateDeadline(ctx context.Context, db bun.IDB, s MarinaScope, ifMatch int, d *Deadline) error {
	return updateDeadline(ctx, db, s, ifMatch, d, deadlineColumns)
}

// UpdateDeadlineAndNotified is UpdateDeadline also writing notified_at (the engine resets it when the due date
// of the source changes).
func UpdateDeadlineAndNotified(ctx context.Context, db bun.IDB, s MarinaScope, ifMatch int, d *Deadline) error {
	return updateDeadline(ctx, db, s, ifMatch, d, append(slices.Clone(deadlineColumns), "notified_at"))
}

func updateDeadline(ctx context.Context, db bun.IDB, s MarinaScope, ifMatch int, d *Deadline, cols []string) error {
	res, err := db.NewUpdate().Model(d).Column(cols...).Set("version = version + 1").
		Where("marina_id = ?", s.ID()).Where("id = ?", d.ID).Where("version = ?", ifMatch).Exec(ctx)
	if err != nil {
		return err
	}
	if affected(res) == 0 {
		if _, err := GetDeadline(ctx, db, s, d.ID); err != nil {
			return err
		}
		return ErrVersionMismatch
	}
	d.Version = ifMatch + 1
	return nil
}

// urgencyExpr returns the SQL predicate (and its arguments) selecting the deadlines with an urgency.
func urgencyExpr(f DeadlineFilter) (string, []any) {
	kinds := make([]string, 0, len(f.SoonUntil))
	for k := range f.SoonUntil {
		kinds = append(kinds, k)
	}
	sort.Strings(kinds)
	// soon: due_on <= the last "due soon" date of its kind.
	var parts []string
	var args []any
	for _, k := range kinds {
		parts = append(parts, "(kind = ? AND due_on <= ?)")
		args = append(args, k, f.SoonUntil[k])
	}
	if len(kinds) > 0 {
		parts = append(parts, "(kind NOT IN (?) AND due_on <= ?)")
		args = append(args, bun.List(kinds), f.DefaultSoonUntil)
	} else {
		parts = append(parts, "(due_on <= ?)")
		args = append(args, f.DefaultSoonUntil)
	}
	soon := "(" + strings.Join(parts, " OR ") + ")"
	switch f.Urgency {
	case UrgencyOverdue:
		return "due_on < ?", []any{f.Today}
	case UrgencyDueSoon:
		return "due_on >= ? AND " + soon, append([]any{f.Today}, args...)
	default: // later
		return "due_on >= ? AND NOT " + soon, append([]any{f.Today}, args...)
	}
}

// ListDeadlines returns a page of deadlines ordered by due date, then id.
func ListDeadlines(ctx context.Context, db bun.IDB, s MarinaScope, f DeadlineFilter, cursor string, limit int) (Page[Deadline], error) {
	limit = ClampLimit(limit)
	afterDue, afterID, err := decodeDeadlineCursor(cursor)
	if err != nil {
		return Page[Deadline]{}, err
	}
	rows := []Deadline{}
	q := db.NewSelect().Model(&rows).Where("marina_id = ?", s.ID())
	if len(f.Statuses) > 0 {
		q = q.Where("status IN (?)", bun.List(f.Statuses))
	}
	if f.Kind != "" {
		q = q.Where("kind = ?", f.Kind)
	}
	if f.CustomerID != "" {
		if !ValidID(f.CustomerID) {
			return Page[Deadline]{Items: rows}, nil
		}
		q = q.Where("customer_id = ?", f.CustomerID)
	}
	if f.VesselID != "" {
		if !ValidID(f.VesselID) {
			return Page[Deadline]{Items: rows}, nil
		}
		q = q.Where("vessel_id = ?", f.VesselID)
	}
	if cv := f.CustomerOrVessels; cv != nil {
		vids := validIDs(cv.VesselIDs)
		if len(vids) > 0 {
			q = q.Where("(customer_id = ? OR vessel_id IN (?))", cv.CustomerID, bun.List(vids))
		} else {
			q = q.Where("customer_id = ?", cv.CustomerID)
		}
	}
	if !f.DueBefore.IsZero() {
		q = q.Where("due_on <= ?", f.DueBefore)
	}
	if !f.DueAfter.IsZero() {
		q = q.Where("due_on >= ?", f.DueAfter)
	}
	if f.Urgency != "" {
		expr, args := urgencyExpr(f)
		q = q.Where(expr, args...)
	}
	if afterID != "" {
		q = q.Where("(due_on > ? OR (due_on = ? AND id > ?))", afterDue, afterDue, afterID)
	}
	if err := q.OrderExpr("due_on, id").Limit(int64(limit + 1)).Scan(ctx); err != nil {
		return Page[Deadline]{}, err
	}
	if len(rows) > limit {
		rows = rows[:limit]
		return Page[Deadline]{Items: rows, NextCursor: encodeDeadlineCursor(&rows[len(rows)-1])}, nil
	}
	return Page[Deadline]{Items: rows}, nil
}

// ListDeadlinePolicies returns the stored policies of a marina, ordered by kind.
func ListDeadlinePolicies(ctx context.Context, db bun.IDB, s MarinaScope) ([]DeadlinePolicy, error) {
	out := []DeadlinePolicy{}
	err := db.NewSelect().Model(&out).Where("marina_id = ?", s.ID()).OrderExpr("kind").Scan(ctx)
	return out, err
}

// ReplaceDeadlinePolicies deletes the stored policies of a marina and inserts ps.
func ReplaceDeadlinePolicies(ctx context.Context, db bun.IDB, s MarinaScope, ps []DeadlinePolicy) error {
	if _, err := db.NewDelete().Table("deadline_policies").Where("marina_id = ?", s.ID()).Exec(ctx); err != nil {
		return err
	}
	if len(ps) == 0 {
		return nil
	}
	_, err := db.NewInsert().Model(&ps).Exec(ctx)
	return err
}

// MarinaTimezone returns the IANA time zone of a marina.
func MarinaTimezone(ctx context.Context, db bun.IDB, s MarinaScope) (string, error) {
	var tz string
	err := db.NewSelect().Table("marinas").Column("timezone").Where("id = ?", s.ID()).Limit(1).Scan(ctx, &tz)
	return tz, notFound(err)
}

// MarinaSettings returns the settings document of a marina.
func MarinaSettings(ctx context.Context, db bun.IDB, s MarinaScope) (JSON, error) {
	var settings JSON
	err := db.NewSelect().Table("marinas").Column("settings").Where("id = ?", s.ID()).Limit(1).Scan(ctx, &settings)
	return settings, notFound(err)
}
