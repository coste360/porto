// Command genkit writes kitassets_gen.go from the illustration kit manifest (assets/harbor-kits/porto-basic):
// the set of asset ids that layout.ValidAsset accepts.
//
// It runs through `go generate ./internal/domain/layout/...` from the internal/domain/layout directory:
// genkit <manifest.json> <output.go>. The SVG files themselves are checked and sanitised by
// web/scripts/gen-harbor-kit.mjs.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os" //nolint:depguard // code generator, not part of the pure package: it reads the manifest and writes the table
	"regexp"
)

type manifest struct {
	Format string `json:"format"`
	ID     string `json:"id"`
	Assets []struct {
		ID       string `json:"id"`
		Category string `json:"category"`
		LabelKey string `json:"label_key"`
	} `json:"assets"`
}

var idPattern = regexp.MustCompile(`^[a-z][a-z0-9_]{0,63}$`)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: genkit <manifest.json> <output.go>")
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var m manifest
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&m); err != nil {
		log.Fatalf("manifest: %v", err)
	}
	if m.Format != "porto-harbor-kit/1" || m.ID == "" || len(m.Assets) == 0 {
		log.Fatalf("manifest: unexpected format %q / id %q / %d assets", m.Format, m.ID, len(m.Assets))
	}
	seen := map[string]bool{}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/domain/layout/internal/genkit; DO NOT EDIT.\n\n")
	b.WriteString("package layout\n\n")
	fmt.Fprintf(&b, "// kitAssetOrder lists the assets of the %q kit in manifest order.\n", m.ID)
	b.WriteString("var kitAssetOrder = []string{\n")
	for _, a := range m.Assets {
		if !idPattern.MatchString(a.ID) || seen[a.ID] {
			log.Fatalf("manifest: invalid or duplicate asset id %q", a.ID)
		}
		seen[a.ID] = true
		fmt.Fprintf(&b, "\t%q,\n", a.ID)
	}
	b.WriteString("}\n\n")
	b.WriteString("var kitAssets = map[string]struct{}{\n")
	for _, a := range m.Assets {
		fmt.Fprintf(&b, "\t%q: {},\n", a.ID)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil { //nolint:gosec // generated source file, world-readable by design
		log.Fatal(err)
	}
}
